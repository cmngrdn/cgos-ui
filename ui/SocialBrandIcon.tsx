/** The 9 canonical social platform keys this atom ships a glyph for. */
export type SocialBrandKey = keyof typeof BRAND_PATHS

export interface SocialBrandIconProps {
  /**
   * Platform key. The 9 `SocialBrandKey` members get a glyph; any other
   * `string` renders nothing (returns `null`) — so callers can pass a looser
   * key (e.g. a value off `Object.entries`) without a cast and degrade
   * gracefully.
   */
  platform: SocialBrandKey | (string & {})
  /** Square px size. Default 19. */
  size?: number
  /** Optional class hook for sizing / color overrides. */
  className?: string
  /** Inline style passthrough (composed last). */
  style?: CSSProperties
}

export function SocialBrandIcon({
  platform,
  size = 19,
  className,
  style,
}: SocialBrandIconProps) {
  const d = (BRAND_PATHS as Record<string, string>)[platform]
  if (!d) return null
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      className={className}
      style={style}
      aria-hidden
      focusable={false}
    >
      <path d={d} />
    </svg>
  )
}
